import type { ChangeCommit } from "@open-cr-agent/core";
import { describe, expect, it } from "vitest";
import { GitLabApi } from "./client.js";
import { gitlabCommit } from "./commit.js";

const API = "https://gitlab.example.com/api/v4/projects/g%2Fp";
const HEAD = "a".repeat(40);
const COMMIT = "c".repeat(40);

const commit: ChangeCommit = {
  parent: HEAD,
  message: "docs: add docstrings generated by ocra",
  files: [
    { path: "src/retry.ts", content: "x\n", created: false, executable: false },
    { path: "src/retry.test.ts", content: "y\n", created: true, executable: false },
  ],
};

interface Script {
  sourceProject?: number;
  branchHead?: string;
  canPush?: boolean;
  commitStatus?: number;
  commitMessage?: string;
}

function gitlab(script: Script = {}) {
  const calls: { method: string; path: string; body?: unknown }[] = [];
  const json = (status: number, value: unknown) =>
    new Response(JSON.stringify(value), {
      status,
      headers: { "Content-Type": "application/json" },
    });
  const fetchImpl = (async (url: string, init?: RequestInit) => {
    const path = url.replace(API, "");
    const method = init?.method ?? "GET";
    calls.push({ method, path, ...(init?.body ? { body: JSON.parse(init.body as string) } : {}) });
    const answers: Record<string, () => Response> = {
      "GET /merge_requests/4": () =>
        json(200, {
          source_branch: "feat/retry",
          source_project_id: script.sourceProject ?? 1,
          target_project_id: 1,
        }),
      "GET /repository/branches/feat%2Fretry": () =>
        json(200, { commit: { id: script.branchHead ?? HEAD }, can_push: script.canPush ?? true }),
      [`GET /repository/files/src%2Fretry.ts?ref=${HEAD}`]: () =>
        json(200, { last_commit_id: "l".repeat(40) }),
      "POST /repository/commits": () =>
        script.commitStatus
          ? json(script.commitStatus, { message: script.commitMessage ?? "" })
          : json(201, { id: COMMIT }),
    };
    return answers[`${method} ${path}`]?.() ?? json(404, { message: "404 Not Found" });
  }) as typeof fetch;
  const api = new GitLabApi("g/p", {
    token: "t",
    baseUrl: "https://gitlab.example.com/api/v4",
    fetch: fetchImpl,
  });
  return { api, calls };
}

describe("gitlabCommit", () => {
  it("commits on the source branch, guarding each file against a push in between", async () => {
    const { api, calls } = gitlab();
    expect(await gitlabCommit(api, 4, commit)).toEqual({ committed: true, sha: COMMIT });
    expect(calls.find((c) => c.method === "POST")?.body).toEqual({
      branch: "feat/retry",
      commit_message: commit.message,
      actions: [
        {
          action: "update",
          file_path: "src/retry.ts",
          content: "x\n",
          last_commit_id: "l".repeat(40),
        },
        { action: "create", file_path: "src/retry.test.ts", content: "y\n" },
      ],
    });
  });

  it("writes nothing to a fork's branch or one the token may not push to", async () => {
    const fork = gitlab({ sourceProject: 2 });
    expect(await gitlabCommit(fork.api, 4, commit)).toMatchObject({ outcome: "not_writable" });
    expect(fork.calls.filter((c) => c.method === "POST")).toEqual([]);
    const locked = gitlab({ canPush: false });
    expect(await gitlabCommit(locked.api, 4, commit)).toMatchObject({ outcome: "not_writable" });
    expect(locked.calls.filter((c) => c.method === "POST")).toEqual([]);
  });

  it("writes nothing once the branch moved, before or while it commits", async () => {
    const moved = gitlab({ branchHead: "b".repeat(40) });
    expect(await gitlabCommit(moved.api, 4, commit)).toMatchObject({ outcome: "head_moved" });
    expect(moved.calls.filter((c) => c.method === "POST")).toEqual([]);
    const raced = gitlab({
      commitStatus: 400,
      commitMessage:
        "You are attempting to update a file that has changed since you started editing it.",
    });
    expect(await gitlabCommit(raced.api, 4, commit)).toMatchObject({ outcome: "head_moved" });
    const refused = gitlab({ commitStatus: 403, commitMessage: "403 Forbidden" });
    expect(await gitlabCommit(refused.api, 4, commit)).toMatchObject({ outcome: "not_writable" });
  });
});
