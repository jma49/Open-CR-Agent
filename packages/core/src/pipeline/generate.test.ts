import { describe, expect, it } from "vitest";
import type { AgentRuntime, CompletionRequest } from "../contracts.js";
import { parseUnifiedDiff } from "../diff/parse.js";
import type { VcsAdapter } from "../vcs.js";
import { generateChanges } from "./generate.js";

const HEAD = "h".repeat(40);
const RETRY = "export function retry(limit: number) {\n  return limit > 0;\n}\n";

function added(path: string, content: string): string {
  const lines = content.split("\n").slice(0, -1);
  return [
    `diff --git a/${path} b/${path}`,
    "new file mode 100644",
    "index 0000000..1111111",
    "--- /dev/null",
    `+++ b/${path}`,
    `@@ -0,0 +1,${lines.length} @@`,
    ...lines.map((l) => `+${l}`),
  ].join("\n");
}

function fakeVcs(files: Record<string, string>, listed: Record<string, string[]> = {}) {
  const reads: string[] = [];
  const diff = Object.entries(files)
    .filter(([path]) => !path.startsWith("old/"))
    .map(([path, content]) => added(path, content))
    .join("\n");
  const vcs: VcsAdapter = {
    name: "fake",
    getChangeRequest: async () => ({
      id: "1",
      title: "Add retries",
      description: "",
      baseSha: "b".repeat(40),
      headSha: HEAD,
    }),
    getDiff: async () => parseUnifiedDiff(diff),
    readFile: async (path) => {
      reads.push(path);
      return files[path] ?? files[`old/${path}`];
    },
    listFiles: async (dir) => listed[dir] ?? [],
    searchCode: async () => [],
    getPriorReview: async () => undefined,
    publish: async () => ({ warnings: [] }),
  };
  return { vcs, reads };
}

function runtime(answer: (request: CompletionRequest) => unknown) {
  const requests: CompletionRequest[] = [];
  const fake: AgentRuntime = {
    name: "fake",
    runTask: () => {
      throw new Error("generate runs no review task");
    },
    complete: async (request) => {
      requests.push(request);
      const text = answer(request);
      if (text instanceof Error) throw text;
      return {
        text: JSON.stringify(text),
        usage: {
          inputTokens: 5,
          outputTokens: 2,
          reasoningTokens: 0,
          cachedTokens: 0,
          costUsd: 0.01,
        },
      };
    },
  };
  return { fake, requests };
}

function generate(kind: "tests" | "docstrings", vcs: VcsAdapter, fake: AgentRuntime) {
  let spent = 0;
  const run = generateChanges({
    kind,
    vcs,
    runtime: fake,
    signal: new AbortController().signal,
    onUsage: (u) => (spent += u.costUsd),
  });
  return run.then((generated) => ({ generated, spent }));
}

describe("generateChanges", () => {
  it("writes a new test beside the source on the writer role, with its example test", async () => {
    const { vcs } = fakeVcs(
      { "src/retry.ts": RETRY, "old/src/upload.test.ts": "import { it } from 'vitest';\n" },
      { src: ["src/retry.ts", "src/upload.test.ts"] },
    );
    const { fake, requests } = runtime(() => ({ content: "it('retries', () => {});" }));
    const { generated, spent } = await generate("tests", vcs, fake);
    expect(requests.map((r) => r.agent)).toEqual(["writer"]);
    expect(requests[0]?.user).toContain("import { it } from 'vitest';");
    expect(requests[0]?.user).toContain("Write the test file: src/retry.test.ts");
    expect(generated.edits).toEqual([
      { kind: "create", path: "src/retry.test.ts", content: "it('retries', () => {});\n" },
    ]);
    expect(generated.commit).toMatchObject({
      parent: HEAD,
      files: [{ path: "src/retry.test.ts", created: true, executable: false }],
    });
    expect(generated.commit?.message).toMatch(
      /^test: add tests generated by ocra for src\/retry\.ts\n/,
    );
    expect(generated.commit?.message).toContain("ocra did not run these tests");
    expect(spent).toBe(0.01);
  });

  it("never writes over a test that is already at the path", async () => {
    const { vcs } = fakeVcs({ "src/retry.ts": RETRY, "old/src/retry.test.ts": "kept\n" });
    const { fake, requests } = runtime(() => ({ content: "replaced" }));
    const { generated } = await generate("tests", vcs, fake);
    expect(requests).toEqual([]);
    expect(generated.edits).toEqual([]);
    expect(generated.commit).toBeUndefined();
    expect(generated.skipped).toEqual([
      { path: "src/retry.ts", reason: "src/retry.test.ts already exists" },
    ]);
  });

  it("never reads or writes for a secret file the change touches", async () => {
    const { vcs, reads } = fakeVcs({ "config/.env.ts": "export const key = 'k';\n" });
    const { fake, requests } = runtime(() => ({ content: "x" }));
    const { generated } = await generate("tests", vcs, fake);
    expect(requests).toEqual([]);
    expect(reads).toEqual([]);
    expect(generated.edits).toEqual([]);
  });

  it("inserts only doc comments, and refuses a reply that would change a line", async () => {
    const { vcs } = fakeVcs({ "src/retry.ts": RETRY, "src/upload.ts": RETRY });
    const { fake } = runtime((request) =>
      request.user.includes('path="src/retry.ts"')
        ? { insertions: [{ after: 0, lines: ["/** Whether to retry. */"] }] }
        : { insertions: [{ after: 1, lines: ["  return true;"] }] },
    );
    const { generated } = await generate("docstrings", vcs, fake);
    expect(generated.edits).toHaveLength(1);
    expect(generated.edits[0]).toMatchObject({
      kind: "insert",
      path: "src/retry.ts",
      content: `/** Whether to retry. */\n${RETRY}`,
    });
    expect(generated.skipped).toEqual([
      { path: "src/upload.ts", reason: "what goes after line 1 is not a doc comment" },
    ]);
    expect(generated.commit?.files).toEqual([
      {
        path: "src/retry.ts",
        content: generated.edits[0]?.content,
        created: false,
        executable: false,
      },
    ]);
    expect(generated.commit?.message).toMatch(/^docs: add docstrings generated by ocra/);
  });

  it("records one file's failed call, and fails only when every call failed", async () => {
    const { vcs } = fakeVcs({ "src/retry.ts": RETRY, "src/upload.ts": `${RETRY}\n` });
    const some = runtime((request) =>
      request.user.includes('path="src/upload.ts"') ? new Error("model down") : { content: "t" },
    );
    const { generated } = await generate("tests", vcs, some.fake);
    expect(generated.edits.map((e) => e.path)).toEqual(["src/retry.test.ts"]);
    expect(generated.skipped).toEqual([{ path: "src/upload.ts", reason: "model down" }]);
    const none = runtime(() => new Error("model down"));
    await expect(generate("tests", vcs, none.fake)).rejects.toThrow("model down");
  });

  it("keeps a path a file named in the change cannot break out of the commit message", async () => {
    const { vcs } = fakeVcs({ "src/a\u0085Signed-off-by: x.ts": RETRY });
    const { fake } = runtime(() => ({ content: "t" }));
    const { generated } = await generate("tests", vcs, fake);
    const subject = generated.commit?.message.split("\n")[0];
    expect(subject).not.toContain("\u0085");
  });
});
