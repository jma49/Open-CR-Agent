import { parseJsonAnswer } from "../agent/json.js";
import type { OneShot } from "../agent/model-call.js";
import type { AgentCallSettings } from "../agent/settings.js";
import { OcraError } from "../errors.js";
import { changedRanges, insertDocComments, type Written } from "./edits.js";
import {
  buildDocPrompt,
  buildTestPrompt,
  type DocRequest,
  docResponseSchema,
  type TestRequest,
  testResponseSchema,
} from "./prompt.js";
import type { GenerateKind } from "./targets.js";

const GENERATE_TIMEOUT_MS = 180_000;
const MAX_TEST_CHARS = 24_000;
const SUBJECT_CHARS = 72;

export interface WriteOptions {
  ask: OneShot;
  signal: AbortSignal;
  call?: AgentCallSettings | undefined;
}

// One plain completion on the writer role (ADR-0051); the path is ocra's,
// the model writes only the content.
export async function writeTest(request: TestRequest, options: WriteOptions): Promise<Written> {
  const answer = await complete(buildTestPrompt(request), options);
  const parsed = testResponseSchema.safeParse(parseJsonAnswer(answer));
  if (!parsed.success) throw invalid("the test is not the expected JSON");
  const content = parsed.data.content.trim();
  if (content === "") return { ok: false, reason: "the model found nothing to test" };
  if (content.length > MAX_TEST_CHARS) {
    return { ok: false, reason: `the test is over ${MAX_TEST_CHARS} characters` };
  }
  return { ok: true, edit: { kind: "create", path: request.testPath, content: `${content}\n` } };
}

export async function writeDocComments(
  request: Omit<DocRequest, "ranges">,
  options: WriteOptions,
): Promise<Written> {
  const ranges = changedRanges(request.diff);
  const answer = await complete(buildDocPrompt({ ...request, ranges }), options);
  const parsed = docResponseSchema.safeParse(parseJsonAnswer(answer));
  if (!parsed.success) throw invalid("the doc comments are not the expected JSON");
  return insertDocComments(
    request.diff.newPath,
    request.source,
    parsed.data.insertions,
    ranges,
    request.language.doc,
  );
}

async function complete(
  prompt: { system: string; user: string },
  options: WriteOptions,
): Promise<string> {
  return options.ask(
    {
      tier: "standard",
      agent: "writer",
      call: options.call,
      system: prompt.system,
      user: prompt.user,
      timeoutMs: GENERATE_TIMEOUT_MS,
    },
    options.signal,
  );
}

function invalid(message: string): OcraError {
  return new OcraError("RUNTIME_INVALID_OUTPUT", message);
}

// The subject names the source files, the body every file written. Paths
// come from the change under review: one line each, without control
// characters, so none can add a trailer or a line of its own.
export function commitMessage(
  kind: GenerateKind,
  sources: readonly string[],
  written: readonly string[],
): string {
  const clean = (paths: readonly string[]) =>
    paths.map((p) => p.replace(/[\p{Cc}\p{Cf}\u2028\u2029]+/gu, " "));
  const [type, what] = kind === "tests" ? ["test", "tests"] : ["docs", "docstrings"];
  const subject = `${type}: add ${what} generated by ocra`;
  const named = `${subject} for ${clean(sources).join(", ")}`;
  const note =
    kind === "tests"
      ? "ocra did not run these tests: it runs no code from the repository. Run them before merging."
      : "ocra only inserted comment lines; no existing line changed.";
  return [
    named.length <= SUBJECT_CHARS ? named : subject,
    "",
    ...clean(written).map((p) => `- ${p}`),
    "",
    note,
  ].join("\n");
}
