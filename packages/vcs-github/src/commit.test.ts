import type { ChangeCommit } from "@open-cr-agent/core";
import type { MergeSource } from "@open-cr-agent/vcs-platform";
import { describe, expect, it } from "vitest";
import { code } from "./adapter.fakes.js";
import { GitHubAdapter } from "./adapter.js";
import { GitHubApi } from "./client.js";
import { githubBaseHead, githubCommit, githubPushBranch } from "./commit.js";

const HEAD = "a".repeat(40);
const COMMIT = "c".repeat(40);
const PULL = { owner: "o", repo: "r", number: 7 };

const commit: ChangeCommit = {
  parent: HEAD,
  message: "docs: add docstrings generated by ocra",
  files: [
    { path: "bin/run.py", content: "x\n", created: false, executable: true },
    { path: "src/a.test.ts", content: "y\n", created: true, executable: false },
  ],
};

interface Call {
  method: string;
  path: string;
  body?: unknown;
}

function github(head: Record<string, unknown> = {}, refStatus = 200, refMessage = "") {
  const calls: Call[] = [];
  const json = (status: number, value: unknown) =>
    new Response(JSON.stringify(value), {
      status,
      headers: { "Content-Type": "application/json" },
    });
  const fetchImpl = (async (url: string, init?: RequestInit) => {
    const path = url.replace("https://api.github.com/repos/o/r", "");
    const call: Call = { method: init?.method ?? "GET", path };
    if (init?.body) call.body = JSON.parse(init.body as string);
    calls.push(call);
    const answers: Record<string, () => Response> = {
      "GET /pulls/7": () =>
        json(200, {
          head: { sha: HEAD, ref: "feat/retry", repo: { full_name: "O/r" }, ...head },
          base: { ref: "release/1.x" },
        }),
      "GET /git/ref/heads/release/1.x": () => json(200, { object: { sha: COMMIT } }),
      [`GET /git/commits/${HEAD}`]: () => json(200, { tree: { sha: "t1" } }),
      "POST /git/trees": () => json(201, { sha: "t2" }),
      "POST /git/commits": () => json(201, { sha: COMMIT }),
      "PATCH /git/refs/heads/feat/retry": () => json(refStatus, { message: refMessage }),
    };
    return answers[`${call.method} ${path}`]?.() ?? json(404, { message: "Not Found" });
  }) as typeof fetch;
  const api = new GitHubApi({ owner: "o", repo: "r" }, { token: "t", fetch: fetchImpl });
  return { api, calls };
}

describe("githubCommit", () => {
  it("writes one commit on the head it read and moves the branch without force", async () => {
    const { api, calls } = github();
    expect(await githubCommit(api, PULL, commit)).toEqual({ committed: true, sha: COMMIT });
    const body = (method: string, path: string) =>
      calls.find((c) => c.method === method && c.path === path)?.body;
    expect(body("POST", "/git/trees")).toEqual({
      base_tree: "t1",
      tree: [
        { path: "bin/run.py", mode: "100755", type: "blob", content: "x\n" },
        { path: "src/a.test.ts", mode: "100644", type: "blob", content: "y\n" },
      ],
    });
    expect(body("POST", "/git/commits")).toEqual({
      message: commit.message,
      tree: "t2",
      parents: [HEAD],
    });
    expect(body("PATCH", "/git/refs/heads/feat/retry")).toEqual({ sha: COMMIT, force: false });
  });

  it("writes nothing to a fork's branch", async () => {
    const { api, calls } = github({ repo: { full_name: "someone/r" } });
    expect(await githubCommit(api, PULL, commit)).toMatchObject({
      committed: false,
      outcome: "not_writable",
    });
    const deleted = github({ repo: null });
    expect(await githubCommit(deleted.api, PULL, commit)).toMatchObject({
      outcome: "not_writable",
    });
    expect(calls.filter((c) => c.method !== "GET")).toEqual([]);
  });

  it("writes nothing once the branch moved past the head it read", async () => {
    const { api, calls } = github({ sha: "b".repeat(40) });
    expect(await githubCommit(api, PULL, commit)).toMatchObject({ outcome: "head_moved" });
    expect(calls.filter((c) => c.method !== "GET")).toEqual([]);
  });

  it("tells a push in between from a refusal when the branch is updated", async () => {
    const raced = github({}, 422, "Update is not a fast forward");
    expect(await githubCommit(raced.api, PULL, commit)).toMatchObject({ outcome: "head_moved" });
    const protectedBranch = github({}, 422, "Protected branch update failed");
    expect(await githubCommit(protectedBranch.api, PULL, commit)).toMatchObject({
      outcome: "not_writable",
    });
    const readOnly = github({}, 403, "Resource not accessible by integration");
    expect(await githubCommit(readOnly.api, PULL, commit)).toMatchObject({
      outcome: "not_writable",
    });
  });
});

describe("a merge pushed from the clone", () => {
  it("reads the base branch's head as it is now", async () => {
    expect(await githubBaseHead(github().api, 7)).toBe(COMMIT);
  });

  it("names the source branch, and refuses a fork's", async () => {
    expect(await githubPushBranch(github().api, PULL)).toEqual({ branch: "feat/retry" });
    const fork = github({ repo: { full_name: "someone/r" } });
    expect(await githubPushBranch(fork.api, PULL)).toEqual({
      refused: "the branch is on a fork, which ocra's token cannot write to",
    });
  });
});

describe("the author of a merge pushed from the clone", () => {
  async function author(baseUrl: string, userId: number) {
    const pull = {
      number: 7,
      title: "Retry",
      body: null,
      html_url: "https://github.com/o/r/pull/7",
      user: { login: "author" },
      base: { sha: COMMIT, ref: "main" },
      head: { sha: HEAD, ref: "feat/retry", repo: { full_name: "o/r" } },
    };
    const fetchImpl = (async (url: string) =>
      new Response(JSON.stringify(url.includes("/users/") ? { id: userId } : pull), {
        status: 200,
        headers: { "Content-Type": "application/json" },
      })) as typeof fetch;
    const pushed: Parameters<MergeSource["push"]>[0][] = [];
    const merge: MergeSource = {
      conflicts: async () => undefined,
      push: async (made) => {
        pushed.push(made);
        return { committed: true, sha: COMMIT };
      },
    };
    await new GitHubAdapter({
      pullRequest: PULL,
      api: new GitHubApi({ owner: "o", repo: "r" }, { token: "t", fetch: fetchImpl, baseUrl }),
      code,
      botLogin: "ocra-cloud[bot]",
      requestChanges: false,
      merge,
    }).commit({ ...commit, mergeParent: COMMIT });
    return pushed[0]?.author;
  }

  it("is the bot's address with its account id, which GitHub links to the account", async () => {
    expect(await author("https://api.github.com", 337575901)).toEqual({
      name: "ocra-cloud[bot]",
      email: "337575901+ocra-cloud[bot]@users.noreply.github.com",
    });
  });

  it("is on a GitHub Enterprise server's own host", async () => {
    expect((await author("https://git.corp.test/api/v3", 12))?.email).toBe(
      "12+ocra-cloud[bot]@users.noreply.git.corp.test",
    );
  });
});
